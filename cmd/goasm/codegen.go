package main

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"strings"
)

type Generator struct {
	arch    string
	encoder Encoder
}

type Encoder interface {
	Encode(instr Instruction, params []Parameter) (string, error)
}

func NewGenerator(arch string, encoder Encoder) *Generator {
	return &Generator{
		arch:    arch,
		encoder: encoder,
	}
}

func (g *Generator) Generate(w io.Writer, templates []Template) error {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by goasm. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package jit\n\n")

	for _, t := range templates {
		if err := g.generateTemplate(&buf, t); err != nil {
			return err
		}
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// If formatting fails, still write the unformatted code for debugging
		fmt.Printf("Formatting failed. Raw output:\n%s\n", buf.String())
		return fmt.Errorf("error formatting generated code: %v", err)
	}

	_, err = w.Write(formatted)
	return err
}

func (g *Generator) generateTemplate(w io.Writer, t Template) error {
	var params []string
	for _, p := range t.Params {
		params = append(params, fmt.Sprintf("%s %s", p.Name, p.Type))
	}

	var retTypes []string
	var retNames []string
	for _, p := range t.Returns {
		retTypes = append(retTypes, p.Type)
		retNames = append(retNames, p.Name)
	}

	retSignature := ""
	if len(retTypes) > 0 {
		retSignature = fmt.Sprintf(" (%s)", strings.Join(retTypes, ", "))
	}

	fmt.Fprintf(w, "func (e *Emitter) Emit%s(%s)%s {\n", t.Name, strings.Join(params, ", "), retSignature)

	if len(retNames) > 0 {
		for _, p := range t.Returns {
			fmt.Fprintf(w, "\tvar %s %s\n", p.Name, p.Type)
		}
	}

	for _, instr := range t.Instrs {
		if instr.Label != "" {
			fmt.Fprintf(w, "\t// Label: %s\n", instr.Label)
			continue
		}

		code, err := g.encoder.Encode(instr, t.Params)
		if err != nil {
			return fmt.Errorf("error encoding instruction %s in template %s: %v", instr.Mnemonic, t.Name, err)
		}

		lines := strings.Split(code, "\n")
		for _, line := range lines {
			fmt.Fprintf(w, "\t%s\n", line)
		}
	}

	if len(retNames) > 0 {
		fmt.Fprintf(w, "\treturn %s\n", strings.Join(retNames, ", "))
	}

	fmt.Fprintf(w, "}\n\n")
	return nil
}
